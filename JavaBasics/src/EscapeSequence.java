public class EscapeSequence {
    static void main() {
        String message = "Hello \"Ankita\"";
        System.out.println(message);

        String path = "c:\\Windows";
        System.out.println(path);

        String greet = "Hey Nancy! \nHow are you?";
        System.out.println(greet);

        System.out.println("Name\tLocation");
        System.out.println("Mike\tPune");
    }
}
